CREATE TABLE user_preferences (
    id BIGSERIAL PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
    archetype_id BIGINT REFERENCES archetypes(id),
    cost_weight DOUBLE PRECISION NOT NULL DEFAULT 0.30,
    time_weight DOUBLE PRECISION NOT NULL DEFAULT 0.30,
    comfort_weight DOUBLE PRECISION NOT NULL DEFAULT 0.20,
    safety_weight DOUBLE PRECISION NOT NULL DEFAULT 0.10,
    eco_weight DOUBLE PRECISION NOT NULL DEFAULT 0.10,
    version INTEGER NOT NULL DEFAULT 1,
    updated_at TIMESTAMP NOT NULL DEFAULT NOW()
);
